'use strict';
// Local-only tests for the ACTUAL G1 money-input private archive reader.
// Synthetic human-written text is a fixture, NEVER a provider response or
// proof of sale quality. No OpenAI, GitHub API, merchant or network calls.
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const viewer=require('./qa-launch-g1-money-private-review');
const runner=require('./qa-launch-g1-money-single-call');
const capture=require('./report-core-paid-full-prompt-capture').capture;
const cost=require('./report-adaptive-v1-offline-cost-plan');
const reader=require('./report-reader-policy');
const {INPUT,MODEL}=require('./qa-launch-g1-money-preflight');
let network=0;
const old=global.fetch;
global.fetch=()=>{network++;throw Error('LAUNCH_G1_REVIEW_NETWORK_MUST_NOT_RUN')};
(async()=>{
 try{
  const cap=await capture(INPUT);
  assert.equal(cap.status,'captured-full-paid-composition');
  assert.equal(cap.providerCalls,0);
  const request=cost.envelope(cap.prompt,MODEL);
  const hash=require('node:crypto').createHash('sha256')
   .update(JSON.stringify(request)).digest('hex');
  assert.equal(hash,runner.REQUEST_SHA);
  const attempt={
   kind:'launch-g1-money-first-chapter-one-attempt',
   status:'charge-possible-no-retry',requestHash:hash,
   model:MODEL,commit:'a'.repeat(40),runId:999987,
   providerCallsAllowed:1,customerSaleApproved:false,
   releaseVerdict:'not-approved'
  };
  const base={
   kind:'launch-g1-money-one-call-qa',status:'stopped-no-retry',
   providerCallsAttempted:1,originalResponseSaved:false,
   automatedValidated:false,releaseVerdict:'not-approved'
  };
  const missing=viewer.build({attempt,summary:base});
  assert.equal(missing.status,'no-usable-first-chapter-do-not-retry');
  assert.equal(missing.noAutomatedRetry,true);
  assert.equal(missing.comparison,null);
  assert(viewer.renderHtml(missing).includes('출시 불가'));
  const rawBase={
   kind:'launch-g1-money-first-chapter-private-provider-response',
   model:MODEL,requestHash:hash,providerCalls:1,request,
   usage:{input_tokens:99,output_tokens:88},
   releaseVerdict:'not-approved'
  };
  const failedSummary={...base,originalResponseSaved:true};
  const incomplete=viewer.build({attempt,summary:failedSummary,
   raw:{...rawBase,response:{status:'incomplete',partialOutput:'<script>alert(1)</script>'}}});
  assert.equal(incomplete.status,'no-usable-first-chapter-do-not-retry');
  const failureHtml=viewer.renderHtml(incomplete);
  assert(!failureHtml.includes('<script>alert(1)</script>'));
  assert(failureHtml.includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
  // Use the existing four-paragraph MANUALLY authored buyer example only
  // as a source-shaped negative/positive reviewer fixture. It was NOT
  // generated by the model and is NOT qualified for sale.
  const authored=fs.readFileSync(path.join(__dirname,
   'qa/work85-authored-first-paid-hour-money-reader-1982-0715-0220-20261124.md'),'utf8');
  const start=authored.indexOf('### 적금을 그대로 둘까');
  const end=authored.indexOf('## 내부 출처 확인');
  assert(start>=0&&end>start);
  const money=authored.slice(start,end).replace(/^### [^\n]+\n/,'')
   .replace(/\*/g,'').trim();
  const month='태어난 달에는 기본 풀이가 있어 겉글자와 중심 숨은 글자의 전통적 뜻을 간단히 설명합니다.';
  const title='출생시간에서 새롭게 비교할 적금과 대출';
  const judgment='출생시간에서는 자원을 마련하는 질문이 책임을 살피는 질문을 뒷받침하는 전통적인 관계로 풀이합니다.';
  const paragraphs={
   temperament:{label:'출생시간에서 추가된 선택 질문',text:money,
    basis:{refs:['natal.hour.stem','natal.hour.hidden.癸']}},
   strength:{label:'기존 무료 출생월 복습',text:month,
    basis:{refs:['natal.month.stem','natal.month.hidden.己']}}
  };
  const raw={...rawBase,response:{chapters:{saju_core:{
   title,keyJudgment:judgment,paragraphs}}}};
  const human=viewer.build({attempt,summary:failedSummary,raw});
  assert.equal(human.kind,'launch-g1-money-private-result-review-v1');
  assert(human.comparison,'review must be generated from actual-style raw first chapter');
  assert.equal(human.comparison.paid.paragraphs.length,2);
  assert.deepEqual(human.comparison.paid.paragraphs.map(x=>x.id),
   ['temperament','strength']);
  assert(human.comparison.freeCards.some(c=>c.id==='birth-month'));
  assert(human.comparison.paid.paragraphs[0].text.includes('대출을 상환하는 경우'));
  assert.equal(human.customerSaleApproved,false);
  assert.equal(human.additionalModelCalls,0);
  const html=viewer.renderHtml(human);
  assert(html.includes('출생시간에서 추가된 선택 질문'));
  assert(html.includes('동일 명식')||html.includes('같은 출생정보'));
  assert(html.includes('유료 첫 장'));
  assert(html.includes('무료'));
  assert(html.includes('고객 판매 불가'));
  assert(!html.includes('<script>alert(1)</script>'));
  // Assert byte-for-byte raw/verified paragraph matching on a COMPLETE
  // machine-success record; a changed verified text MUST fail closed.
  const checked={id:'saju_core',
   title:reader.plainText(title),keyJudgment:reader.plainText(judgment),
   bodyTopics:['temperament','strength'],
   bodyLabels:[reader.plainText(paragraphs.temperament.label),
    reader.plainText(paragraphs.strength.label)],
   body:[reader.plainText(money),reader.plainText(month)]};
  const summaryOk={...failedSummary,status:'first-chapter-machine-validated',
   automatedValidated:true};
  const validated={
   kind:'launch-g1-money-automated-first-chapter-check',
   model:MODEL,machineValidation:'passed-not-human-reviewed',
   batches:[{ids:['saju_core'],completedSections:1,sections:[checked]}],
   releaseVerdict:'not-approved'
  };
  const success=viewer.build({attempt,summary:summaryOk,raw,validated});
  assert.equal(success.machineReportedPass,true);
  assert.equal(success.humanEditorialReviewRequired,true);
  assert.equal(success.customerSaleApproved,false);
  assert.throws(()=>viewer.build({attempt,summary:summaryOk,raw,
   validated:{...validated,batches:[{...validated.batches[0],
    sections:[{...checked,body:[money,'tampered month']}]}]}}),
   /validated-prose-differs-from-original-provider-output/);
  assert.throws(()=>viewer.build({attempt,summary:failedSummary,
   raw:{...raw,requestHash:'0'.repeat(64)}}),
   /raw-money-request-or-model-identity-mismatch/);
  assert.throws(()=>viewer.build({attempt,summary:failedSummary,
   raw:{...raw,response:{...raw.response,cover:{}}}}),
   /not-the-single-first-chapter-structured-body/);
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'launch-g1-local-review-'));
  try{
   for(const [key,file] of Object.entries(viewer.NAMES)){
    if(key==='validated')continue;
    const value={attempt,raw,summary:failedSummary}[key];
    fs.writeFileSync(path.join(temp,file),JSON.stringify(value));
   }
   const out=path.join(temp,'review-private.html');
   const wrote=viewer.main([temp,out]);
   assert.equal(wrote.customerSaleApproved,false);
   assert(fs.readFileSync(out,'utf8').includes('적금을'));
   assert.throws(()=>viewer.main([temp,out]),/review-output-must-be-new/);
  }finally{fs.rmSync(temp,{recursive:true,force:true})}
  assert.equal(network,0);
  console.log('PASS launch G1: actual-money free-vs-original private review, missing/invalid/machine-passed outputs, tamper check; NO provider call/sale');
 }finally{global.fetch=old}
})().catch(err=>{console.error(err);process.exitCode=1});
